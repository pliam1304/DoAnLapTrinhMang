using System.Security.Cryptography;
using Nega.Common.Protocol;

namespace Nega.Common.Security;

/// <summary>
/// Trình nạp cấu hình bảo mật và thông số mạng từ biến môi trường hoặc tệp .env cục bộ (không đẩy lên GitHub).
/// Nếu chưa cấu hình .env, hệ thống tự động dùng giá trị mặc định an toàn để ứng dụng vẫn chạy hợp lý ngay khi clone.
/// </summary>
public sealed class NegaRuntimeConfig
{
    private static readonly Lazy<NegaRuntimeConfig> LazyInstance = new(LoadInternal);
    public static NegaRuntimeConfig Current => LazyInstance.Value;

    public int UdpPort { get; init; } = ProtocolConstants.DefaultUdpDiscoveryPort;
    public int TcpPort { get; init; } = ProtocolConstants.DefaultTcpControlPort;
    public int HttpPort { get; init; } = ProtocolConstants.DefaultDashboardHttpPort;
    public string BindHost { get; init; } = "0.0.0.0";
    public string ServerDisplayName { get; init; } = "NEGA-LAB-SERVER";

    // Bảo mật cụm mạng & quản trị
    public string ClusterKey { get; init; } = string.Empty;
    public string AdminPin { get; init; } = string.Empty;
    public bool IsAdminPinAutoGenerated { get; init; }
    public bool RequirePinOnLocalhost { get; init; }

    // Cổng an toàn hệ điều hành (mặc định tắt để tránh thao tác nhầm khi thử nghiệm)
    public bool AllowRealShutdown { get; init; }
    public bool AllowRealOsCapture { get; init; }
    public bool MaskHostIdentity { get; init; } = true;
    public int DefaultSimulatedCount { get; init; } = 5;

    private static NegaRuntimeConfig LoadInternal()
    {
        var envValues = LoadDotEnvUpwards();

        string Get(string key, string fallback = "")
        {
            string? osVal = Environment.GetEnvironmentVariable(key);
            if (!string.IsNullOrWhiteSpace(osVal))
            {
                return osVal.Trim();
            }
            return envValues.TryGetValue(key, out string? fileVal) && !string.IsNullOrWhiteSpace(fileVal)
                ? fileVal.Trim()
                : fallback;
        }

        int GetInt(string key, int fallback, int min, int max)
        {
            string raw = Get(key);
            return int.TryParse(raw, out int parsed) ? Math.Clamp(parsed, min, max) : fallback;
        }

        bool GetBool(string key, bool fallback)
        {
            string raw = Get(key);
            if (string.IsNullOrEmpty(raw)) return fallback;
            return raw.Equals("1", StringComparison.OrdinalIgnoreCase) ||
                   raw.Equals("true", StringComparison.OrdinalIgnoreCase) ||
                   raw.Equals("yes", StringComparison.OrdinalIgnoreCase);
        }

        string configuredPin = Get("NEGA_ADMIN_PIN");
        bool isAutoPin = string.IsNullOrWhiteSpace(configuredPin);
        if (isAutoPin)
        {
            // Sinh mã PIN ngẫu nhiên theo phiên chạy nếu người dùng chưa thiết lập .env
            configuredPin = RandomNumberGenerator.GetInt32(100000, 999999).ToString();
        }

        return new NegaRuntimeConfig
        {
            UdpPort = GetInt("NEGA_UDP_PORT", ProtocolConstants.DefaultUdpDiscoveryPort, 1024, 65535),
            TcpPort = GetInt("NEGA_TCP_PORT", ProtocolConstants.DefaultTcpControlPort, 1024, 65535),
            HttpPort = GetInt("NEGA_HTTP_PORT", ProtocolConstants.DefaultDashboardHttpPort, 1024, 65535),
            BindHost = Get("NEGA_BIND_HOST", "0.0.0.0"),
            ServerDisplayName = Get("NEGA_SERVER_NAME", "NEGA-LAB-SERVER"),
            ClusterKey = Get("NEGA_CLUSTER_KEY"),
            AdminPin = configuredPin,
            IsAdminPinAutoGenerated = isAutoPin,
            RequirePinOnLocalhost = GetBool("NEGA_REQUIRE_PIN_ON_LOCALHOST", false),
            AllowRealShutdown = GetBool("NEGA_ALLOW_REAL_SHUTDOWN", false),
            AllowRealOsCapture = GetBool("NEGA_ALLOW_OS_CAPTURE", false),
            MaskHostIdentity = GetBool("NEGA_MASK_HOST_IDENTITY", true),
            DefaultSimulatedCount = GetInt("NEGA_DEFAULT_SIMULATED_COUNT", 5, 0, 16)
        };
    }

    private static Dictionary<string, string> LoadDotEnvUpwards()
    {
        var dict = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        string[] startDirs = { Directory.GetCurrentDirectory(), AppContext.BaseDirectory };

        foreach (string start in startDirs)
        {
            var dir = new DirectoryInfo(start);
            for (int depth = 0; depth < 6 && dir is not null; depth++)
            {
                string envFile = Path.Combine(dir.FullName, ".env");
                if (File.Exists(envFile))
                {
                    foreach (string rawLine in File.ReadAllLines(envFile))
                    {
                        string line = rawLine.Trim();
                        if (string.IsNullOrEmpty(line) || line.StartsWith('#'))
                        {
                            continue;
                        }

                        int eqIdx = line.IndexOf('=');
                        if (eqIdx <= 0)
                        {
                            continue;
                        }

                        string k = line[..eqIdx].Trim();
                        string v = line[(eqIdx + 1)..].Trim();
                        if ((v.StartsWith('"') && v.EndsWith('"') && v.Length >= 2) ||
                            (v.StartsWith('\'') && v.EndsWith('\'') && v.Length >= 2))
                        {
                            v = v[1..^1];
                        }

                        dict.TryAdd(k, v);
                    }
                    return dict;
                }
                dir = dir.Parent;
            }
        }

        return dict;
    }
}

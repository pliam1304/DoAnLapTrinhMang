using Nega.Common.Security;
using Nega.Server.Bridge;
using Nega.Server.Discovery;
using Nega.Server.State;
using Nega.Server.TcpServer;

var cfg = NegaRuntimeConfig.Current;
var builder = WebApplication.CreateBuilder(args);

builder.WebHost.UseUrls($"http://{cfg.BindHost}:{cfg.HttpPort}");
builder.Logging.ClearProviders();
builder.Logging.AddConsole();
builder.Logging.SetMinimumLevel(LogLevel.Warning);

// Đăng ký rõ ràng các tầng dịch vụ của Nega Server:
// 1. Tầng Quản lý Trạng thái & Đo đạc (State & Telemetry)
builder.Services.AddSingleton<WorkstationRegistry>();
builder.Services.AddSingleton<TelemetryService>();

// 2. Tầng Khám phá LAN bằng UDP Broadcast
builder.Services.AddSingleton(sp => new UdpDiscoveryService(
    sp.GetRequiredService<WorkstationRegistry>(),
    sp.GetRequiredService<TelemetryService>(),
    cfg.UdpPort,
    cfg.TcpPort));
builder.Services.AddHostedService(sp => sp.GetRequiredService<UdpDiscoveryService>());

// 3. Tầng Điều khiển & Nhận luồng JPEG qua TCP
builder.Services.AddSingleton(sp => new TcpControlServer(
    sp.GetRequiredService<WorkstationRegistry>(),
    sp.GetRequiredService<TelemetryService>(),
    cfg.TcpPort));
builder.Services.AddHostedService(sp => sp.GetRequiredService<TcpControlServer>());

// 4. Tầng Agent cục bộ & Giả lập Phòng máy (Simulator qua UDP/TCP thật)
builder.Services.AddSingleton(sp => new LabSimulatorService(
    sp.GetRequiredService<TelemetryService>(),
    cfg.UdpPort,
    cfg.TcpPort));
builder.Services.AddHostedService(sp => sp.GetRequiredService<LabSimulatorService>());

var app = builder.Build();

app.UseDefaultFiles();
app.UseStaticFiles();

// 5. Tầng Cầu nối API & Luồng JPEG cho Nega Dashboard UI (kèm xác thực PIN từ LAN)
app.MapNegaApi();

Console.WriteLine("=====================================================================");
Console.WriteLine("  NEGA - PHẦN MỀM GIÁM SÁT PHÒNG MÁY & REMOTE CONTROL MINI");
Console.WriteLine($"  • Giao diện Nega Dashboard : http://localhost:{cfg.HttpPort}");
Console.WriteLine($"  • Kênh UDP Broadcast LAN   : Port {cfg.UdpPort}");
Console.WriteLine($"  • Kênh TCP JPEG & Control  : Port {cfg.TcpPort}");
Console.WriteLine($"  • Xác thực Cụm LAN (HMAC)  : {(string.IsNullOrWhiteSpace(cfg.ClusterKey) ? "Chế độ Dev mở (chưa đặt NEGA_CLUSTER_KEY trong .env)" : "Đã bật HMAC-SHA256")}");
Console.WriteLine($"  • Tắt máy thật (OS)        : {(cfg.AllowRealShutdown ? "CHO PHÉP" : "ĐÃ KHÓA AN TOÀN (Chỉ chạy Safe Mode)")}");
Console.WriteLine($"  • Mã PIN quản trị qua LAN  : {(cfg.IsAdminPinAutoGenerated ? $"{cfg.AdminPin} (Tự sinh theo phiên)" : "Đã nạp từ .env cục bộ")}");
Console.WriteLine("=====================================================================");

await app.RunAsync();
